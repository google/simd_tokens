//! Feature marker traits for SIMD capabilities.
//!
//! Every trait in this module is an `unsafe` marker trait with no methods.
//! `#[simd_entry]` adds these traits as bounds on the token parameter, one per
//! feature listed in the function's `#[target_feature(enable = ...)]`.
//!
//! # Safety
//!
//! Implementors of any feature marker trait in this module must ensure that a
//! value of the implementing type can only be constructed if the corresponding
//! CPU target feature is supported by the current CPU at runtime for the
//! lifetime of the process. Safe code generated by `#[simd_entry]` relies on
//! this guarantee to invoke `#[target_feature]` functions without `unsafe`.
//! Prefer the predefined tokens in [`crate::tokens`], whose implementations
//! enforce this invariant via compile-time `cfg(target_feature)` and runtime
//! detection in `try_new()`.

#[cfg(target_arch = "aarch64")]
mod aarch64;
#[cfg(target_arch = "aarch64")]
pub use aarch64::*;

#[cfg(any(target_arch = "x86", target_arch = "x86_64"))]
mod x86;
#[cfg(any(target_arch = "x86", target_arch = "x86_64"))]
pub use x86::*;

#[cfg(not(any(target_arch = "aarch64", target_arch = "x86", target_arch = "x86_64",)))]
mod unsupported;
#[cfg(not(any(target_arch = "aarch64", target_arch = "x86", target_arch = "x86_64",)))]
pub(crate) use unsupported::__impl_feature_trait;
